"""
Gradient-weighted Class Activation Mapping (Grad-CAM) Implementation.

Provides visual explanations for deep convolutional neural networks classifying
chest radiographs (NORMAL vs PNEUMONIA).
"""

import io
from pathlib import Path
from typing import Tuple, Optional, Union, Any
import numpy as np
from PIL import Image
import matplotlib as mpl
import tensorflow as tf


def make_gradcam_heatmap(
    img_array: np.ndarray,
    model: tf.keras.Model,
    last_conv_layer_name: str = "conv4_features",
    target_class_idx: int = 1
) -> np.ndarray:
    """
    Computes a 2D Grad-CAM heatmap for an input image.

    Parameters:
    -----------
    img_array : np.ndarray
        Preprocessed image tensor of shape (1, H, W, 3) in float32.
    model : tf.keras.Model
        Trained Keras model (e.g., Baseline CNN or MobileNetV2).
    last_conv_layer_name : str
        Name of the target convolutional layer to extract feature activations from.
    target_class_idx : int
        Index of the target class to explain (1 for PNEUMONIA, 0 for NORMAL).

    Returns:
    --------
    heatmap : np.ndarray
        2D normalized activation map with values in range [0, 1].
    """
    # Check if the target layer exists directly or in a nested backbone
    is_nested_backbone = False
    nested_backbone_name = None

    if last_conv_layer_name not in [l.name for l in model.layers]:
        # Search inside nested layers (e.g. MobileNetV2 backbone)
        for layer in model.layers:
            if hasattr(layer, "layers") and last_conv_layer_name in [sub.name for sub in layer.layers]:
                is_nested_backbone = True
                nested_backbone_name = layer.name
                break

    if is_nested_backbone:
        # Handle nested transfer learning model (e.g. MobileNetV2)
        base = model.get_layer(nested_backbone_name)
        target_conv_layer = base.get_layer(last_conv_layer_name)
        base_feature_model = tf.keras.models.Model(inputs=base.input, outputs=target_conv_layer.output)

        head_input = tf.keras.Input(shape=target_conv_layer.output.shape[1:])
        x = head_input
        # Trace layers after the backbone
        start_head = False
        for l in model.layers:
            if start_head:
                x = l(x)
            elif l.name == nested_backbone_name:
                start_head = True
        head_model = tf.keras.models.Model(inputs=head_input, outputs=x)

        with tf.GradientTape() as tape:
            conv_outputs = base_feature_model(img_array)
            tape.watch(conv_outputs)
            predictions = head_model(conv_outputs)
            # Binary sigmoid output: score for PNEUMONIA is pred, NORMAL is 1 - pred
            if target_class_idx == 1:
                class_channel = predictions[:, 0]
            else:
                class_channel = 1.0 - predictions[:, 0]

        grads = tape.gradient(class_channel, conv_outputs)
        pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
        conv_outputs = conv_outputs[0]
        heatmap = conv_outputs @ pooled_grads[..., tf.newaxis]
        heatmap = tf.squeeze(heatmap)

    else:
        # Standard flat functional or sequential model (e.g. Baseline CNN)
        last_conv_layer = model.get_layer(last_conv_layer_name)
        grad_model = tf.keras.models.Model(
            inputs=model.input,
            outputs=[last_conv_layer.output, model.output]
        )

        with tf.GradientTape() as tape:
            conv_outputs, predictions = grad_model(img_array)
            if target_class_idx == 1:
                class_channel = predictions[:, 0]
            else:
                class_channel = 1.0 - predictions[:, 0]

        grads = tape.gradient(class_channel, conv_outputs)
        pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
        conv_outputs = conv_outputs[0]
        heatmap = conv_outputs @ pooled_grads[..., tf.newaxis]
        heatmap = tf.squeeze(heatmap)

    # Apply ReLU: keep only features that positively correlate with the target class
    heatmap = tf.maximum(heatmap, 0.0)
    max_val = tf.math.reduce_max(heatmap)
    if max_val > 0:
        heatmap = heatmap / max_val

    return heatmap.numpy()


def generate_gradcam_overlay(
    original_img: Union[Image.Image, np.ndarray, str, Path],
    heatmap: np.ndarray,
    alpha: float = 0.4,
    colormap_name: str = "jet"
) -> Tuple[Image.Image, Image.Image]:
    """
    Superimposes a Grad-CAM heatmap onto the original chest radiograph.

    Parameters:
    -----------
    original_img : Image, np.ndarray, or Path
        The original input chest X-ray image.
    heatmap : np.ndarray
        2D normalized heatmap [0, 1] generated by `make_gradcam_heatmap`.
    alpha : float
        Opacity of the colorized heatmap overlay (0.0 to 1.0).
    colormap_name : str
        Colormap to apply (default: 'jet').

    Returns:
    --------
    Tuple[Image.Image, Image.Image]
        (colorized_heatmap, blended_overlay)
    """
    if isinstance(original_img, (str, Path)):
        img = Image.open(original_img).convert("RGB")
    elif isinstance(original_img, np.ndarray):
        if original_img.max() <= 1.0:
            original_img = (original_img * 255.0).astype(np.uint8)
        img = Image.fromarray(original_img.astype(np.uint8)).convert("RGB")
    else:
        img = original_img.convert("RGB")

    target_size = img.size  # (width, height)

    # Resize raw heatmap to match the original image dimensions using BICUBIC interpolation
    heatmap_img = Image.fromarray(np.uint8(255 * heatmap))
    heatmap_resized = heatmap_img.resize(target_size, resample=Image.Resampling.BICUBIC)
    heatmap_resized_arr = np.array(heatmap_resized) / 255.0

    # Colorize using Matplotlib colormap
    cmap = mpl.colormaps.get(colormap_name, mpl.colormaps["jet"])
    colored_heatmap_arr = cmap(heatmap_resized_arr)[:, :, :3]  # drop alpha channel
    colored_heatmap = Image.fromarray(np.uint8(255 * colored_heatmap_arr))

    # Blend original grayscale image and colored heatmap
    blended = Image.blend(img, colored_heatmap, alpha=alpha)

    return colored_heatmap, blended


def explain_chest_xray(
    img_input: Union[str, Path, Image.Image, Any],
    model: tf.keras.Model,
    last_conv_layer_name: str = "conv4_features",
    target_size: Tuple[int, int] = (224, 224),
    alpha: float = 0.4
) -> dict:
    """
    End-to-end diagnostic explanation pipeline for a single chest X-ray.

    Parameters:
    -----------
    img_input : str, Path, PIL.Image.Image, or file-like object
        Path to the chest X-ray image or in-memory image.
    model : tf.keras.Model
        Loaded prediction model.
    last_conv_layer_name : str
        Target convolutional layer name.
    target_size : tuple
        Expected input dimensions (e.g. (224, 224)).
    alpha : float
        Heatmap overlay opacity.

    Returns:
    --------
    dict containing:
        - 'predicted_label': 'NORMAL' or 'PNEUMONIA'
        - 'confidence': float (probability percentage)
        - 'prob_pneumonia': float
        - 'prob_normal': float
        - 'heatmap': np.ndarray (raw 2D heatmap)
        - 'colored_heatmap': PIL.Image
        - 'blended_image': PIL.Image
        - 'original_image': PIL.Image
    """
    if isinstance(img_input, Image.Image):
        pil_img = img_input.convert("RGB")
        img_source = "in_memory_image"
    elif isinstance(img_input, (str, Path)):
        img_path = Path(img_input)
        pil_img = Image.open(img_path).convert("RGB")
        img_source = str(img_path)
    elif hasattr(img_input, "read"):
        pil_img = Image.open(img_input).convert("RGB")
        img_source = getattr(img_input, "name", "stream_image")
    else:
        raise ValueError(f"Unsupported image input type: {type(img_input)}")

    pil_resized = pil_img.resize(target_size, resample=Image.Resampling.BILINEAR)

    img_arr = np.array(pil_resized, dtype=np.float32)
    img_batch = np.expand_dims(img_arr, axis=0)

    # Model inference
    pred_prob = float(model.predict(img_batch, verbose=0)[0][0])
    is_pneumonia = pred_prob >= 0.5
    predicted_label = "PNEUMONIA" if is_pneumonia else "NORMAL"
    target_class_idx = 1 if is_pneumonia else 0
    confidence = (pred_prob if is_pneumonia else (1.0 - pred_prob)) * 100.0

    # Generate Grad-CAM Heatmap
    heatmap = make_gradcam_heatmap(
        img_array=img_batch,
        model=model,
        last_conv_layer_name=last_conv_layer_name,
        target_class_idx=target_class_idx
    )

    colored_cam, blended = generate_gradcam_overlay(
        original_img=pil_resized,
        heatmap=heatmap,
        alpha=alpha
    )

    return {
        "image_path": img_source,
        "predicted_label": predicted_label,
        "confidence": round(confidence, 2),
        "prob_pneumonia": round(pred_prob * 100.0, 2),
        "prob_normal": round((1.0 - pred_prob) * 100.0, 2),
        "heatmap": heatmap,
        "colored_heatmap": colored_cam,
        "blended_image": blended,
        "original_image": pil_resized
    }
